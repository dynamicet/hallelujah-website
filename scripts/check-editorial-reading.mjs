import assert from 'node:assert/strict'
import { setTimeout as delay } from 'node:timers/promises'
import { runVisualCheck } from './lib/visual-check.mjs'
const base = process.env.HH_PREVIEW_URL || 'http://localhost:3000'
async function waitFor(page, expression) {
  for (let i = 0; i < 100; i++) { if (await page.eval(expression)) return; await delay(100) }
  assert.fail('Timed out: ' + expression)
}
async function enter(page) {
  await page.send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13, text: '\r' })
  await page.send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13 })
}
await runVisualCheck('editorial-reading', base, async ({ browser, output }) => {
  for (const width of [390, 768, 1440]) {
    const page = await browser.newPage({ width, height: 1000, mobile: width < 600 })
    await page.goto(base)
    await page.eval("document.querySelector('[data-editorial-card] a').scrollIntoView({block:'center',behavior:'instant'}); document.querySelector('[data-editorial-card] a').focus({preventScroll:true})")
    await enter(page)
    await waitFor(page, "Boolean(document.querySelector('[data-editorial-reader]'))")
    await delay(700)
    assert.equal(await page.eval("document.querySelector('[data-editorial-return]').getAttribute('href')"), '/#editorial-make-room-for-your-questions')
    assert.equal(await page.eval("document.querySelectorAll('.article-reading-guide a').length"), 3)
    await page.screenshot({ path: output + '/opening-' + width + '.png' })
    await page.eval("document.querySelector('.article-reading-guide a[href=\"#reading-2\"]').focus()")
    await enter(page)
    await delay(900)
    assert.equal(await page.eval("location.hash"), '#reading-2')
    assert.equal(await page.eval("document.activeElement.id"), 'reading-2')
    assert.ok(await page.eval("document.querySelector('#reading-2').getBoundingClientRect().top > 100"))
    assert.ok(await page.eval("Boolean(document.querySelector('.article-reading-guide [aria-current=location]'))"))
    await page.screenshot({ path: output + '/chapter-' + width + '.png' })
    await page.eval("document.querySelector('[data-editorial-return]').focus()")
    await enter(page)
    await waitFor(page, "location.pathname === '/'")
    await delay(900)
    assert.equal(await page.eval("location.hash"), '#editorial-make-room-for-your-questions')
    assert.equal(await page.eval("document.activeElement.id"), 'editorial-make-room-for-your-questions')
    assert.ok(await page.eval("document.activeElement.getBoundingClientRect().top > 100"))
    await page.screenshot({ path: output + '/source-' + width + '.png' })
    await page.goto(base + '/news-resources?category=resources')
    await page.eval("document.querySelector('[data-editorial-card] a').click()")
    await waitFor(page, "Boolean(document.querySelector('[data-editorial-reader]'))")
    assert.equal(await page.eval("document.querySelector('[data-editorial-return]').getAttribute('href')"), '/news-resources?category=resources#editorial-make-room-for-your-questions')
    await page.eval("document.querySelector('[data-editorial-return]').click()")
    await waitFor(page, "location.pathname === '/news-resources'")
    assert.equal(await page.eval("new URLSearchParams(location.search).get('category')"), 'resources')
    await page.eval("history.back()")
    await waitFor(page, "Boolean(document.querySelector('[data-editorial-reader]'))")
    await page.eval("history.forward()")
    await waitFor(page, "location.pathname === '/news-resources'")
    assert.equal(await page.eval("new URLSearchParams(location.search).get('category')"), 'resources')
    await page.goto(base + '/news-resources/a-conversation-about-care?from=https://example.com')
    assert.equal(await page.eval("document.querySelector('.article-reading-guide') === null"), true)
    assert.ok(await page.eval("document.querySelector('[data-editorial-return]').getAttribute('href').startsWith('/news-resources#')"))
    await page.send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] })
    assert.equal(await page.eval("getComputedStyle(document.querySelector('[data-editorial-reader] header')).animationName"), 'none')
    assert.equal(await page.eval("document.documentElement.scrollWidth > innerWidth"), false)
    assert.deepEqual(page.consoleErrors, [])
    await page.close()
    console.log('PASS ' + width + ': keyboard route/section/return focus, source/category retention, short article, reduced motion')
  }
  const page = await browser.newPage({ width: 390, height: 1000, mobile: true })
  await page.send('Emulation.setScriptExecutionDisabled', { value: true })
  await page.goto(base + '/news-resources/make-room-for-your-questions?from=%2F')
  assert.equal(await page.eval("document.querySelectorAll('.article-reading-guide a').length"), 3)
  await page.eval("document.querySelector('.article-reading-guide a').click()")
  assert.equal(await page.eval("location.hash"), '#reading-1')
  assert.equal(await page.eval("document.activeElement.id"), 'reading-1')
  assert.equal(await page.eval("document.querySelector('[data-editorial-return]').getAttribute('href')"), '/#editorial-make-room-for-your-questions')
  await page.close()
  console.log('PASS no-JavaScript section navigation and source return href')
})
