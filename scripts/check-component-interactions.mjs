import assert from 'node:assert/strict'
import { setTimeout as delay } from 'node:timers/promises'
import { runVisualCheck } from './lib/visual-check.mjs'
const base = process.env.HH_PREVIEW_URL || 'http://localhost:3000'
const key = async (page, value, code = value, number = 13) => {
  await page.send('Input.dispatchKeyEvent', { type: 'keyDown', key: value, code, windowsVirtualKeyCode: number, ...(value === 'Enter' ? { text: '\r' } : {}) })
  await page.send('Input.dispatchKeyEvent', { type: 'keyUp', key: value, code, windowsVirtualKeyCode: number })
}
await runVisualCheck('component-interactions', base, async ({ browser, output }) => {
  for (const width of [390, 768, 1440]) {
    const page = await browser.newPage({ width, height: 1000, mobile: width < 600 })
    await page.goto(base)
    assert.ok(await page.eval("Boolean(document.querySelector('[data-public-shell]'))"))
    await page.eval("document.querySelector('#care-query').focus()")
    await page.send('Input.insertText', { text: 'heart' })
    await page.eval("document.querySelector('.care-mode-select[value=doctors]').focus()")
    await key(page, 'ArrowRight', 'ArrowRight', 39)
    await delay(300)
    assert.equal(await page.eval("document.querySelector('.care-mode-select:checked').value"), 'services')
    assert.equal(await page.eval("document.querySelector('#care-query').value"), 'heart')
    assert.ok(await page.eval("document.querySelector('.care-search-panel form').action.endsWith('/services')"))
    assert.equal(await page.eval("document.activeElement.value"), 'services')
    await page.screenshot({ path: output + '/care-' + width + '.png' })
    await page.eval("document.querySelector('#partners').scrollIntoView({block:'start',behavior:'instant'})")
    await delay(800)
    assert.equal(await page.eval("document.querySelector('.partners-billing-list').children.length"), 6)
    const directoryHeight = await page.eval("document.querySelector('.partners-directory').getBoundingClientRect().height")
    await page.eval("document.querySelector('[aria-label=\"Next companies\"]').focus({preventScroll:true})")
    for (const next of [2, 3, 4]) {
      await key(page, 'Enter')
      await delay(700)
      assert.equal(await page.eval("document.querySelector('.partners-pagination strong').textContent"), String(next))
      assert.equal(await page.eval("document.querySelector('.partners-directory').getBoundingClientRect().height"), directoryHeight)
      assert.equal(await page.eval("document.activeElement.getAttribute('aria-label')"), 'Next companies')
    }
    assert.equal(await page.eval("document.activeElement.getAttribute('aria-disabled')"), 'true')
    await key(page, 'Enter')
    await delay(150)
    assert.equal(await page.eval("document.querySelector('.partners-pagination strong').textContent"), '4')
    await page.screenshot({ path: output + '/corporate-last-page-' + width + '.png' })
    await page.eval("document.querySelector('[aria-label=\"Previous companies\"]').focus({preventScroll:true})")
    await key(page, 'Enter')
    await delay(700)
    assert.equal(await page.eval("document.querySelector('.partners-pagination strong').textContent"), '3')
    await page.send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] })
    await key(page, 'Enter')
    await delay(100)
    assert.equal(await page.eval("document.querySelector('.partners-pagination strong').textContent"), '2')
    await key(page, 'Enter')
    await delay(100)
    assert.equal(await page.eval("document.querySelector('.partners-pagination strong').textContent"), '1')
    await page.send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'no-preference' }] })
    // Each list retains its own organizations, including shared identities.
    assert.equal(await page.eval("document.querySelectorAll('.partners-collaboration-list:not(.partners-rail-clone) > li').length"), 10)
    assert.equal(await page.eval("new Set([...document.querySelectorAll('#partners [data-partner]')].map(item => item.dataset.partner)).size"), 19)
    assert.equal(await page.eval("document.querySelectorAll('.partners-billing-list > li').length"), 19)
    await page.screenshot({ path: output + '/partners-' + width + '.png' })
    await page.eval("document.querySelector('.partners-directory').scrollIntoView({block:'end',behavior:'instant'})")
    await page.screenshot({ path: output + '/corporate-controls-' + width + '.png' })
    await page.eval("document.querySelector('.home-care-card').scrollIntoView({block:'center',behavior:'instant'}); document.querySelector('.home-care-card').focus({preventScroll:true})")
    await delay(800)
    await page.screenshot({ path: output + '/card-' + width + '.png' })
    if (width < 1024) {
      await page.eval("scrollTo({top:0,behavior:'instant'}); document.querySelector('[data-menu-trigger]').focus()")
      await key(page, 'Enter')
      await delay(300)
      assert.ok(await page.eval("document.querySelector('[data-navigation-panel]').matches(':popover-open')"))
      await page.screenshot({ path: output + '/menu-' + width + '.png' })
      await page.eval("document.querySelector('[data-navigation-panel] a').focus()")
      await key(page, 'Escape', 'Escape', 27)
      await delay(300)
      assert.equal(await page.eval("document.activeElement.hasAttribute('data-menu-trigger')"), true)
      assert.equal(await page.eval("document.querySelector('[data-navigation-panel]').matches(':popover-open')"), false)
      // Fast close/reopen must finish in the requested state.
      await key(page, 'Enter')
      await key(page, 'Enter')
      await key(page, 'Enter')
      await delay(300)
      assert.ok(await page.eval("document.querySelector('[data-navigation-panel]').matches(':popover-open')"))
      await key(page, 'Escape', 'Escape', 27)
    }
    await page.eval("document.querySelector('#partners').scrollIntoView({block:'center',behavior:'instant'})")
    await page.send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] })
    await delay(150)
    assert.equal(await page.eval("document.querySelector('#partners').getAnimations({subtree:true}).filter(a=>a.playState==='running').length"), 0)
    assert.equal(await page.eval("document.querySelectorAll('.partners-rail-clone').length"), 0)
    assert.equal(await page.eval("getComputedStyle(document.querySelector('.care-mode-options'),'::after').transitionDuration"), '0s')
    assert.equal(await page.eval("document.documentElement.scrollWidth > innerWidth"), false)
    assert.deepEqual(page.consoleErrors, [])
    await page.close()
    console.log('PASS ' + width + ': keyboard care switch/query retention, separate organization lists, fixed-height corporate paging/focus, menu/Escape, reduced motion, overflow')
  }
  const page = await browser.newPage({ width: 390, height: 1000, mobile: true })
  await page.send('Emulation.setScriptExecutionDisabled', { value: true })
  await page.goto(base)
  assert.ok(await page.eval("Boolean(document.querySelector('form[action=\"/services\"]'))"))
  assert.equal(await page.eval("document.querySelector('.partners-motion-toggle') === null"), true)
  assert.ok(await page.eval("document.querySelectorAll('.partners-billing-list > li').length === 19"))
  const firstCompany = await page.eval("document.querySelector('.partners-billing-list').firstElementChild.dataset.partner")
  await page.eval("document.querySelector('.partners-billing-viewport').scrollLeft = document.querySelector('.partners-billing-viewport').clientWidth")
  assert.ok(await page.eval("document.querySelector('.partners-billing-viewport').scrollLeft > 0"))
  assert.equal(await page.eval("document.querySelector('.partners-billing-list').firstElementChild.dataset.partner"), firstCompany)
  await page.eval("document.querySelector('[data-menu-trigger]').click()")
  await delay(300)
  assert.ok(await page.eval("document.querySelector('[data-navigation-panel]').matches(':popover-open')"))
  await page.close()
  console.log('PASS no-JavaScript care fallback, partners and native menu')
})
