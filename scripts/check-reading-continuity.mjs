import assert from 'node:assert/strict'
import { setTimeout as delay } from 'node:timers/promises'
import { runVisualCheck } from './lib/visual-check.mjs'
const base = process.env.HH_PREVIEW_URL || 'http://localhost:3000'
async function enter(page) {
  await page.send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13, text: '\r' })
  await page.send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13 })
}
await runVisualCheck('reading-continuity', base, async ({ browser, output }) => {
  for (const width of [390, 768, 1440]) {
    const page = await browser.newPage({ width, height: 1000, mobile: width < 600 })
    await page.goto(base + '/health-topics')
    await page.eval("document.querySelector('[data-health-library] [aria-controls=health-topic-matches]').click()")
    await delay(200)
    await page.eval("document.querySelector('[data-health-topic]').scrollIntoView({block:'center',behavior:'instant'}); document.querySelector('[data-health-topic]').focus({preventScroll:true})")
    await delay(600)
    const original = await page.eval("({ y: scrollY, id: document.activeElement.dataset.healthTopic, count: document.querySelectorAll('[data-health-topic]').length })")
    await enter(page)
    await delay(400)
    assert.equal(await page.eval("document.activeElement.id"), 'health-topic-reader')
    assert.ok(await page.eval("document.querySelector('#health-topic-reader').getBoundingClientRect().top >= 0"))
    assert.ok(await page.eval("document.querySelector('#health-topic-reader').getBoundingClientRect().top < innerHeight / 2"))
    await page.screenshot({ path: output + '/reader-' + width + '.png' })
    await page.eval("document.querySelector('#health-topic-reader button').focus()")
    await enter(page)
    await delay(350)
    assert.equal(await page.eval("document.activeElement.dataset.healthTopic"), original.id)
    assert.equal(await page.eval("document.querySelectorAll('[data-health-topic]').length"), original.count)
    assert.ok(Math.abs(await page.eval("scrollY") - original.y) < 3, 'return restores scroll position')
    assert.equal(await page.eval("document.activeElement.dataset.lastRead"), 'true')
    await page.screenshot({ path: output + '/returned-' + width + '.png' })
    await page.goto(base)
    await page.eval("document.querySelector('.everyday-account summary').scrollIntoView({block:'start',behavior:'instant'}); document.querySelector('.everyday-account summary').focus({preventScroll:true})")
    await delay(600)
    await enter(page)
    await delay(400)
    assert.ok(await page.eval("document.querySelector('.everyday-account').open"))
    await page.screenshot({ path: output + '/story-' + width + '.png' })
    await page.eval("document.querySelector('.everyday-account .story-reading-return').focus()")
    await enter(page)
    await delay(400)
    assert.equal(await page.eval("document.querySelector('.everyday-account').open"), false)
    assert.ok(await page.eval("document.activeElement === document.querySelector('.everyday-account summary')"))
    assert.ok(await page.eval("document.activeElement.getBoundingClientRect().top >= 0"))
    await page.eval("document.querySelector('.everyday-film summary').click(); document.querySelector('.story-cinema[open] .everyday-transcript summary').click()")
    await delay(400)
    await page.eval("document.querySelector('.story-cinema[open] .everyday-transcript .story-reading-return').focus()")
    await enter(page)
    await delay(400)
    assert.equal(await page.eval("document.querySelector('.story-cinema[open] .everyday-transcript').open"), false)
    assert.ok(await page.eval("document.querySelector('.story-cinema[open]')"))
    assert.ok(await page.eval("document.activeElement === document.querySelector('.story-cinema[open] .everyday-transcript summary')"))
    await page.eval("document.querySelector('.story-cinema[open]').close()")
    await page.send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] })
    await page.eval("document.querySelector('.everyday-account summary').click()")
    assert.equal(await page.eval("getComputedStyle(document.querySelector('.everyday-account .story-reading-body'),'::before').animationName"), 'none')
    assert.equal(await page.eval("document.documentElement.scrollWidth > innerWidth"), false)
    assert.deepEqual(page.consoleErrors, [])
    await page.close()
    console.log('PASS ' + width + ': reader focus, original result/scroll return, story/transcript keyboard return, reduced motion, overflow/errors')
  }
  const page = await browser.newPage({ width: 390, height: 1000, mobile: true })
  await page.send('Emulation.setScriptExecutionDisabled', { value: true })
  await page.goto(base)
  await page.eval("document.querySelector('.everyday-account summary').click()")
  assert.ok(await page.eval("document.querySelector('.everyday-account').open"))
  assert.equal(await page.eval("getComputedStyle(document.querySelector('.story-reading-return')).display"), 'none')
  await page.close()
  console.log('PASS native story disclosure without JavaScript')
})
