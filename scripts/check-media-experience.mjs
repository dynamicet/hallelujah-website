import assert from 'node:assert/strict'
import { setTimeout as delay } from 'node:timers/promises'
import { runVisualCheck } from './lib/visual-check.mjs'
const base = process.env.HH_PREVIEW_URL || 'http://localhost:3000'
async function waitFor(page, expression) {
  for (let i = 0; i < 100; i++) { if (await page.eval(expression)) return; await delay(100) }
  assert.fail('Timed out: ' + expression)
}
async function enter(page) {
  await page.send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13, text: '\r' })
  await page.send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13 })
}
await runVisualCheck('media-experience', base, async ({ browser, output }) => {
  for (const width of [390, 768, 1440]) {
    const page = await browser.newPage({ width, height: 1000, mobile: width < 600 })
    await page.goto(base)
    await page.eval("document.querySelector('.care-background-film').scrollIntoView({block:'center',behavior:'instant'})")
    await waitFor(page, "!document.querySelector('.care-film-control').hidden")
    await delay(700)
    assert.equal(await page.eval("document.querySelector('.care-background-film video').hasAttribute('src')"), false)
    assert.equal(await page.eval("performance.getEntriesByType('resource').some(r => /home-loop.*\\.(webm|mp4)/.test(r.name))"), false)
    const initialHeight = await page.eval("document.querySelector('.care-background-film').getBoundingClientRect().height")
    await page.screenshot({ path: output + '/poster-' + width + '.png' })
    await page.eval("document.querySelector('.care-film-control').focus({preventScroll:true})")
    // Reproduce the reported missing-label condition before the next state update.
    await page.eval("document.querySelector('[data-film-control-label]').remove()")
    await enter(page)
    await waitFor(page, "document.querySelector('.care-background-film').dataset.filmState === 'playing'")
    assert.equal(await page.eval("document.querySelector('[data-film-control-label]').textContent"), 'Pause film')
    assert.equal(await page.eval("document.querySelector('.care-film-control').querySelectorAll('svg').length"), 2)
    assert.equal(await page.eval("getComputedStyle(document.querySelector('.care-film-about')).visibility"), 'visible')
    assert.equal(await page.eval("document.querySelector('.care-background-film video').loop"), false)
    assert.equal(await page.eval("document.querySelector('.care-background-film').getBoundingClientRect().height"), initialHeight)
    await delay(900)
    await page.screenshot({ path: output + '/playing-' + width + '.png' })
    await enter(page)
    assert.equal(await page.eval("document.querySelector('.care-background-film').dataset.filmState"), 'paused')
    await enter(page)
    await waitFor(page, "document.querySelector('.care-background-film').dataset.filmState === 'playing'")
    await page.eval("scrollTo({top:0,behavior:'instant'})")
    await waitFor(page, "document.querySelector('.care-background-film video').paused")
    await page.eval("document.querySelector('.care-background-film').scrollIntoView({block:'center',behavior:'instant'})")
    await delay(500)
    assert.equal(await page.eval("document.querySelector('.care-background-film video').paused"), true)
    await page.eval("document.querySelector('.care-film-stop').focus()")
    await enter(page)
    assert.equal(await page.eval("document.activeElement.className"), 'care-film-control')
    assert.equal(await page.eval("document.querySelector('.care-background-film video').hasAttribute('src')"), false)
    await enter(page)
    await waitFor(page, "document.querySelector('.care-background-film').dataset.filmState === 'playing'")
    await page.eval("const v=document.querySelector('.care-background-film video'); v.currentTime=v.duration-.1")
    await waitFor(page, "document.querySelector('.care-background-film').dataset.filmState === 'ended'")
    await delay(700)
    await page.screenshot({ path: output + '/ended-' + width + '.png' })
    await page.send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] })
    assert.equal(await page.eval("document.querySelector('.care-background-film video').hasAttribute('src')"), false)
    assert.equal(await page.eval("getComputedStyle(document.querySelector('.care-film-control')).display"), 'none')
    await page.eval("document.querySelector('.everyday-film > summary').scrollIntoView({block:'center',behavior:'instant'}); document.querySelector('.everyday-film > summary').focus()")
    await delay(500)
    await page.screenshot({ path: output + '/portrait-' + width + '.png' })
    await enter(page)
    await delay(500)
    assert.equal(await page.eval("document.querySelector('.story-cinema[open]') !== null"), true)
    assert.equal(await page.eval("document.activeElement === document.querySelector('.story-cinema[open] .story-cinema-close')"), true)
    assert.equal(await page.eval("getComputedStyle(document.querySelector('.story-cinema[open] .story-film-player')).animationName"), 'none')
    await page.eval("document.querySelector('.story-cinema[open] video').scrollIntoView({block:'center',behavior:'instant'}); document.querySelector('.story-cinema[open] video').play()")
    await waitFor(page, "document.querySelector('.story-cinema[open] .story-film-state').textContent.includes('Now playing')")
    await page.screenshot({ path: output + '/story-' + width + '.png' })
    await page.eval("document.querySelector('.story-cinema[open] video').pause()")
    assert.equal(await page.eval("document.querySelector('.story-cinema[open] video').paused"), true)
    await page.eval("document.querySelector('.story-cinema[open] video').scrollIntoView({block:'center',behavior:'instant'}); const storyPlayer=document.querySelector('.story-cinema[open] video'); storyPlayer.currentTime=storyPlayer.duration-.1; storyPlayer.play()")
    await waitFor(page, "document.querySelector('.story-cinema[open] .story-film-continue').dataset.ended === 'true'")
    await page.eval("document.querySelector('.story-cinema[open] .everyday-transcript > summary').focus()")
    await enter(page)
    assert.equal(await page.eval("document.querySelector('.story-cinema[open] .everyday-transcript').open"), true)
    assert.equal(await page.eval("document.activeElement === document.querySelector('.story-cinema[open] .everyday-transcript > summary')"), true)
    assert.ok(await page.eval("document.activeElement.getBoundingClientRect().top > 100"))
    await page.screenshot({ path: output + '/transcript-' + width + '.png' })
    await page.eval("document.querySelector('.story-cinema[open]').close()")
    assert.equal(await page.eval("document.documentElement.scrollWidth > innerWidth"), false)
    assert.deepEqual(page.consoleErrors, [])
    await page.close()
    console.log('PASS ' + width + ': no preactivation media, keyboard playback/stop, finite film, offscreen pause, reduced motion, story playback/offscreen pause')
  }
  const failure = await browser.newPage({ width: 390, height: 1000, mobile: true })
  await failure.send('Page.addScriptToEvaluateOnNewDocument', { source: "Object.defineProperty(navigator, 'connection', {value: {saveData:true}, configurable:true})" })
  await failure.goto(base)
  await failure.eval("document.querySelector('.care-background-film').scrollIntoView({block:'center',behavior:'instant'})")
  await waitFor(failure, "!document.querySelector('.care-film-control').hidden")
  assert.equal(await failure.eval("document.querySelector('.care-background-film video').hasAttribute('src')"), false)
  await failure.send('Network.setBlockedURLs', { urls: ['*home-loop*.webm', '*home-loop*.mp4'] })
  await failure.eval("document.querySelector('.care-film-control').click()")
  await waitFor(failure, "document.querySelector('.care-background-film').dataset.filmState === 'failed'")
  assert.equal(await failure.eval("document.querySelector('.care-background-film video').hasAttribute('src')"), false)
  await failure.screenshot({ path: output + '/failed-390.png' })
  await failure.send('Network.setBlockedURLs', { urls: [] })
  await failure.eval("document.querySelector('.care-film-control').click()")
  await waitFor(failure, "document.querySelector('.care-background-film').dataset.filmState === 'playing'")
  await failure.send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] })
  await waitFor(failure, "!document.querySelector('.care-background-film video').hasAttribute('src')")
  await failure.close()
  console.log('PASS Save-Data opt-in, blocked media/poster recovery, retry, live reduced-motion change')
  const page = await browser.newPage({ width: 390, height: 1000, mobile: true })
  await page.send('Emulation.setScriptExecutionDisabled', { value: true })
  await page.goto(base)
  assert.equal(await page.eval("document.querySelector('.care-background-film video').hasAttribute('src')"), false)
  assert.equal(await page.eval("getComputedStyle(document.querySelector('.care-film-control')).display"), 'none')
  await page.close()
  console.log('PASS no-JavaScript poster fallback')
})

