import assert from 'node:assert/strict'
import { writeFileSync } from 'node:fs'
import { Browser, sleep } from '/home/befikadusata/.codex/skills/design-taste-frontend/scripts/lib/cdp.mjs'
const browser = await Browser.launch()
const page = await browser.newPage()
const results = []
const position = () => page.eval(() => document.querySelector('#partners-list').scrollLeft)
const load = async () => {
  await page.goto('http://localhost:3000', { settleMs: 800 })
  await page.eval(() => document.querySelector('#partners').scrollIntoView({behavior:'instant', block:'center'}))
  await page.send('Input.dispatchMouseEvent', {type:'mouseMoved',x:0,y:0})
}
try {
  await page.setViewport({width:1440,height:900})
  await load()
  const initial = await position()
  await sleep(4300)
  assert.ok(await position() > initial, 'Slideshow advances automatically')
  results.push('Automatic sliding')
  await page.eval(() => document.querySelector('.partners-playback').click())
  await sleep(600)
  const paused = await position()
  await sleep(3700)
  assert.equal(await position(), paused, 'Pause stops sliding')
  await page.eval(() => document.querySelector('[aria-label="Next partners"]').click())
  await sleep(700)
  assert.ok(await position() > paused, 'Next works while paused')
  await page.eval(() => document.querySelector('[aria-label="Previous partners"]').click())
  await sleep(700)
  assert.ok(await position() < paused + 100, 'Previous works')
  results.push('Pause and manual next/previous')
  await page.eval(() => document.querySelector('.partners-toggle').click())
  assert.equal(await page.eval(() => document.querySelector('#partners-list').dataset.view), 'all')
  assert.equal(await page.eval(() => document.querySelectorAll('#partners-list li').length),19)
  await page.screenshot({path:'artifacts/n3-review/after/partners-all-1440.jpg',fullPage:true})
  await page.eval(() => document.querySelector('.partners-toggle').click())
  assert.equal(await page.eval(() => document.querySelector('#partners-list').dataset.view),'row')
  results.push('Expand/collapse retains all 19 records')
  await load()
  await page.eval(() => document.querySelector('#partners-list').focus())
  await sleep(600)
  const focused=await position()
  await sleep(3900)
  assert.equal(await position(),focused,'Keyboard focus stops automatic movement')
  results.push('Keyboard focus pauses sliding')
  await load()
  const point=await page.eval(()=>{const r=document.querySelector('#partners-list').getBoundingClientRect();return {x:r.x+30,y:r.y+30}})
  await page.send('Input.dispatchMouseEvent',{type:'mouseMoved',...point})
  await sleep(600)
  const hovered=await position()
  await sleep(3900)
  assert.equal(await position(),hovered,'Hover pauses sliding')
  results.push('Hover pauses sliding')
  await page.send('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'reduce'}]})
  await load()
  await sleep(3900)
  assert.equal(await position(),0,'Reduced motion disables autoplay')
  assert.equal(await page.eval(()=>!!document.querySelector('.partners-playback')),false)
  results.push('Reduced motion disables automatic sliding')
  await page.send('Emulation.setScriptExecutionDisabled',{value:true})
  await load()
  assert.equal(await page.eval(()=>document.querySelectorAll('#partners-list li').length),19)
  assert.equal(await page.eval(()=>getComputedStyle(document.querySelector('.partners-toggle')).display),'none')
  results.push('Without JavaScript, all 19 partners remain in a native scrollable list')
  await page.send('Emulation.setScriptExecutionDisabled',{value:false})
  await page.send('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'no-preference'}]})
  for(const width of [1440,768,390,320]){
    await page.setViewport({width,height:900})
    await load()
    assert.equal(await page.eval(()=>document.documentElement.scrollWidth>innerWidth),false)
    await page.eval(()=>document.documentElement.style.fontSize='200%')
    assert.equal(await page.eval(()=>[...document.querySelectorAll('#partners .partners-heading, #partners .partners-footer, #partners .partners-controls, #partners .partners-controls button')].some(e=>e.getBoundingClientRect().right>innerWidth)),false,'Partner controls fit at 200% root font')
    await page.screenshot({path:`artifacts/n3-review/after/partners-text200-${width}.jpg`})
  }
  results.push('No page overflow at four standard widths; partner controls fit at 200% root-font size')
  console.log(results.join('\n'))
  writeFileSync('artifacts/n3-review/interactions.json',JSON.stringify(results,null,2))
} finally { await browser.close() }
