export function translateInterface(text: string, language: InterfaceLanguage): string {
  if (language === 'en') return text
  const copy = text.trim()
  const direct = Object.hasOwn(amharicInterface, copy) ? amharicInterface[copy] : undefined
  if (direct) return text.replace(copy, direct)
  // Variable UI copy keeps numbers, canonical names and search terms intact.
  const patterns: [RegExp, (...values: string[]) => string][] = [
    [/^Filter clinicians \((\d+)\)$/, (n) => `ሐኪሞችን አጣራ (${n})`],
    [/^Filter services \((\d+)\)$/, (n) => `አገልግሎቶችን አጣራ (${n})`],
    [/^(\d+) results$/, (n) => `${n} ውጤቶች`],
    [/^Showing (\d+)–(\d+) of (\d+)$/, (first, last, total) => `ከ${total} ውስጥ ${first}–${last} በማሳየት ላይ`],
    [/^View profile for (.+)$/, (name) => `የ${name} መገለጫን ይመልከቱ`],
    [/^Request an appointment with (.+)$/, (name) => `ከ${name} ጋር ቀጠሮ ይጠይቁ`],
    [/^Request an appointment for (.+)$/, (name) => `ለ${name} ቀጠሮ ይጠይቁ`],
    [/^Topics beginning with (.+)$/, (letter) => `በ${letter} የሚጀምሩ ርዕሶች`],
    [/^Page (\d+)$/, (n) => `ገጽ ${n}`],
    [/^Go to page (\d+)$/, (n) => `ወደ ገጽ ${n} ይሂዱ`],
    [/^Remove (.+) filter$/, (name) => `የ${name} ማጣሪያን አስወግድ`],
    [/^Call reception: (.+)$/, (number) => `ወደ መቀበያ ይደውሉ፦ ${number}`],
    [/^There (?:is 1 problem|are (\d+) problems) to correct\.$/, (n) => `ለማስተካከል ${n || '1'} ችግሮች አሉ።`],
  ]
  for (const [pattern, format] of patterns) {
    const match = copy.match(pattern)
    if (match) return text.replace(copy, format(...match.slice(1)))
  }
  // Separate trailing arrows from their action labels.
  const action = copy.match(/^(.+?)(\s*[→↑])$/u)
  if (action && Object.hasOwn(amharicInterface, action[1].trim())) return text.replace(copy, `${amharicInterface[action[1].trim()]}${action[2]}`)
  return text
}
