"""Regenerate file-friendly palette data and CSS from palette.json. No dependencies."""
from pathlib import Path
import json

root = Path(__file__).resolve().parent
palette = json.loads((root / 'palette.json').read_text())
(root / 'palette-data.js').write_text('// Generated by generate.py; edit palette.json instead.\nwindow.HALLELUJAH_PALETTE = ' + json.dumps(palette, indent=2) + ';\n')
lines = ['/* Generated catalog tokens; edit palette.json and run generate.py. Runtime tokens have a separate generator. */', ':root {']
for color in palette['colors']:
    lines.append(f'  --hh-{color["id"]}: {color["hex"]};')
    if 'background' in color:
        lines.append(f'  --hh-{color["id"]}-tint: {color["background"]};')
lines.append('')
for role, color in palette['semantic'].items():
    lines.append(f'  --hh-{role}: var(--hh-{color});')
lines.extend(['}', ''])
(root / 'tokens.css').write_text('\n'.join(lines))
